-- Schema initial de DevManager (compatible PostgreSQL et H2)
-- Chaque entreprise (organization) possede ses utilisateurs et ses projets : les donnees sont isolees par entreprise.

CREATE TABLE organizations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL,
    created_at TIMESTAMP    NOT NULL
);

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR(255) NOT NULL,
    last_name       VARCHAR(255) NOT NULL,
    email           VARCHAR(255) NOT NULL UNIQUE,
    password        VARCHAR(255) NOT NULL,
    role            VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMP,
    organization_id BIGINT       NOT NULL REFERENCES organizations (id)
);
CREATE INDEX idx_users_organization ON users (organization_id);

CREATE TABLE projects (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255)   NOT NULL,
    description     VARCHAR(2000),
    status          VARCHAR(20)    NOT NULL,
    budget          NUMERIC(15, 2) NOT NULL,
    start_date      DATE,
    end_date        DATE,
    owner_id        BIGINT         NOT NULL REFERENCES users (id),
    organization_id BIGINT         NOT NULL REFERENCES organizations (id)
);
CREATE INDEX idx_projects_organization ON projects (organization_id);

CREATE TABLE project_members (
    project_id BIGINT NOT NULL REFERENCES projects (id),
    user_id    BIGINT NOT NULL REFERENCES users (id),
    PRIMARY KEY (project_id, user_id)
);

CREATE TABLE expenses (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label      VARCHAR(255)   NOT NULL,
    amount     NUMERIC(15, 2) NOT NULL,
    category   VARCHAR(20)    NOT NULL,
    date       DATE           NOT NULL,
    project_id BIGINT         NOT NULL REFERENCES projects (id)
);
CREATE INDEX idx_expenses_project ON expenses (project_id);

CREATE TABLE messages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id    BIGINT        NOT NULL REFERENCES users (id),
    recipient_id BIGINT        NOT NULL REFERENCES users (id),
    subject      VARCHAR(255)  NOT NULL,
    content      VARCHAR(5000) NOT NULL,
    sent_at      TIMESTAMP,
    is_read      BOOLEAN       NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_messages_recipient ON messages (recipient_id);
CREATE INDEX idx_messages_sender ON messages (sender_id);

CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token      VARCHAR(255) NOT NULL UNIQUE,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    expires_at TIMESTAMP    NOT NULL,
    used       BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE invitations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token           VARCHAR(255) NOT NULL UNIQUE,
    email           VARCHAR(255) NOT NULL,
    role            VARCHAR(20)  NOT NULL,
    organization_id BIGINT       NOT NULL REFERENCES organizations (id),
    invited_by_id   BIGINT       NOT NULL REFERENCES users (id),
    created_at      TIMESTAMP    NOT NULL,
    expires_at      TIMESTAMP    NOT NULL,
    accepted        BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_invitations_organization ON invitations (organization_id);
