ALTER TABLE organizations ADD COLUMN plan VARCHAR(20) DEFAULT 'FREE' NOT NULL;
ALTER TABLE organizations ADD COLUMN current_period_end TIMESTAMP;

-- Historique des paiements (mode demonstration : aucun prelevement reel)
CREATE TABLE payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT         NOT NULL REFERENCES organizations (id),
    amount          NUMERIC(15, 2) NOT NULL,
    currency        VARCHAR(3)     NOT NULL,
    method          VARCHAR(20)    NOT NULL,
    reference       VARCHAR(40)    NOT NULL UNIQUE,
    period_end      TIMESTAMP      NOT NULL,
    created_at      TIMESTAMP      NOT NULL
);
CREATE INDEX idx_payments_organization ON payments (organization_id);
